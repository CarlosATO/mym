import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'

const root = new URL('..', import.meta.url)
const migration = await readFile(new URL('supabase/migrations/20260930185030_adquisiciones_confirm_supplier_review.sql', root), 'utf8')
const action = await readFile(new URL('src/app/actions/adquisiciones/purchase-orders.ts', root), 'utf8')
const review = await readFile(new URL('src/modules/adquisiciones/ordenes-compra/purchase-order-supplier-review.tsx', root), 'utf8')

test('confirmation RPC is locked, secured, validated, and atomic', () => {
  assert.match(migration, /CREATE OR REPLACE FUNCTION adquisiciones\.confirm_purchase_order_supplier_review\(/)
  assert.match(migration, /SECURITY DEFINER/)
  assert.match(migration, /auth\.uid\(\)/)
  assert.match(migration, /p_user_id.*p_company_id/)
  assert.match(migration, /core\.has_company_access/)
  assert.match(migration, /adquisiciones\.po\.update/)
  assert.match(migration, /WHERE id = p_po_id AND company_id = p_company_id[\s\S]*FOR UPDATE/)
  assert.match(migration, /v_po\.status = 'CONFIRMADA'/)
  assert.match(migration, /already_confirmed/)
  assert.match(migration, /v_po\.status <> 'ENVIADA_PROVEEDOR'/)
  assert.match(migration, /receipt_status IS DISTINCT FROM 'PENDIENTE'/)
  assert.match(migration, /quantity_received, 0\) > 0/)
  assert.match(migration, /snapshot_type = 'ORIGINAL_SENT'/)
  assert.match(migration, /v_item_count = 0/)
  assert.match(migration, /i\.quantity <= 0/)
  assert.match(migration, /i\.unit_price <= 0/)
  assert.match(migration, /productos con precio pendiente/)
  assert.match(migration, /discount_percent < 0 OR i\.discount_percent > 100/)
  assert.match(migration, /tax_rate < 0 OR i\.tax_rate > 100/)
  assert.match(migration, /'CONFIRMED'/)
  assert.match(migration, /'sku', pr\.sku/)
  assert.match(migration, /status_before_snapshot', po\.status/)
  assert.match(migration, /SET status = 'CONFIRMADA', updated_by = p_user_id/)
  assert.match(migration, /from_status, to_status, changed_by, reason/)
  assert.match(migration, /'ENVIADA_PROVEEDOR', 'CONFIRMADA'/)
  assert.match(migration, /p_new_status = 'CONFIRMADA'/)
  assert.match(migration, /requiere confirmar la revisión del proveedor/)
  assert.doesNotMatch(migration, /UPDATE adquisiciones\.purchase_order_snapshots/)
})

test('server action authenticates, scopes company, and calls only confirmation RPC', () => {
  const start = action.indexOf('export async function confirmPurchaseOrderSupplierReview')
  const end = action.indexOf('export async function getPurchaseOrderSupplierReviewComparison', start)
  assert.ok(start >= 0 && end > start)
  const source = action.slice(start, end)
  assert.match(source, /supabase\.auth\.getUser\(\)/)
  assert.match(source, /getActiveCompanyId\(\)/)
  assert.match(source, /confirm_purchase_order_supplier_review/)
  assert.match(source, /p_user_id: user\.id/)
  assert.match(source, /p_company_id: companyId/)
  assert.doesNotMatch(source, /update_purchase_order_status/)
  assert.match(review, /confirmPurchaseOrderSupplierReview/)
})

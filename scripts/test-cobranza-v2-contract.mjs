import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'

const migration = await readFile(new URL('../supabase/migrations/20261006140000_collection_workflow_etapa_2a.sql', import.meta.url), 'utf8')
const action = await readFile(new URL('../src/app/actions/comercial/cobranza-workflow.ts', import.meta.url), 'utf8')
const view = await readFile(new URL('../src/modules/analisis-comercial/views/cobranza.tsx', import.meta.url), 'utf8')
const metrics = await readFile(new URL('../src/modules/analisis-comercial/lib/cobranza-metrics.ts', import.meta.url), 'utf8')

test('cliente nuevo comienza en TO_MANAGE', () => assert.match(migration, /stage text NOT NULL DEFAULT 'TO_MANAGE'/))
test('workflow persiste por company_id y client_id', () => assert.match(migration, /UNIQUE \(company_id, client_id\)/))
test('las cuatro etapas están declaradas', () => assert.match(migration, /TO_MANAGE.*IN_PROGRESS.*PAYMENT_COMMITMENT.*FOLLOW_UP/s))
test('cambio de etapa usa upsert multiempresa', () => assert.match(action, /from\('collection_customer_workflow'\)[\s\S]*upsert[\s\S]*company_id: companyId/))
test('cambio de etapa genera evento', () => assert.match(action, /from\('collection_customer_events'\)[\s\S]*event_type: input\.stage === 'PAYMENT_COMMITMENT' \? 'COMMITMENT' : 'STAGE_CHANGED'/))
test('compromiso guarda fecha y monto', () => assert.match(action, /commitment_at[\s\S]*commitment_amount/))
test('historial no tiene UPDATE ni DELETE para service_role', () => {
  assert.match(migration, /GRANT SELECT, INSERT ON TABLE comercial\.collection_customer_events TO service_role/)
  assert.doesNotMatch(migration, /GRANT SELECT, INSERT, UPDATE ON TABLE comercial\.collection_customer_events/)
})
test('acciones validan usuario y empresa activa', () => assert.match(action, /getActiveCompanyId\(user\)[\s\S]*La sesión o la empresa activa/))
test('permiso funcional existe', () => assert.match(migration, /analisis_comercial\.cobranza\.register_payment/))
test('FINANZAS, GERENCIA y SUPER_USUARIO reciben permiso', () => assert.match(migration, /FINANZAS', 'GERENCIA', 'SUPER_USUARIO/))
test('VENDEDOR no recibe permiso por defecto', () => assert.doesNotMatch(migration, /VENDEDOR/))
test('idempotency_key es obligatoria y única por empresa', () => assert.match(migration, /idempotency_key text NOT NULL[\s\S]*UNIQUE \(company_id, idempotency_key\)/))
test('un solo intento activo por documento', () => assert.match(migration, /collection_payment_attempts_active_document_idx[\s\S]*status IN \('CREATED', 'SUBMITTING', 'UNKNOWN'\)/))
test('CONFIRMED y FAILED no están en el lock activo', () => assert.doesNotMatch(migration, /status IN \('CREATED', 'SUBMITTING', 'UNKNOWN', 'CONFIRMED'/))
test('preflight usa bsale_document_id, no folio', () => assert.match(action, /input\.documentId[\s\S]*bsale_document_id/))
test('preflight consulta unpaid_documents live', () => assert.match(action, /\/clients\/unpaid_documents\.json/))
test('preflight rechaza documento ya pagado/no pendiente', () => assert.match(action, /El documento ya no está pendiente en Bsale/))
test('preflight rechaza monto inválido y exceso de saldo', () => {
  assert.match(action, /input\.amount <= 0/)
  assert.match(action, /input\.amount > liveBalance/)
})
test('preflight acepta pagos parciales y totales dentro del saldo', () => assert.match(action, /liveBalance = Number\(liveDocument\.totalAmountOwed\)/))
test('preflight valida forma configurada y activa', () => {
  assert.match(action, /collection_payment_type_config/)
  assert.match(action, /liveType\.active === false/)
})
test('preflight valida cliente del documento', () => assert.match(action, /Number\(document\.client_id\)/))
test('la UI no llama Bsale directamente', () => assert.doesNotMatch(view, /payments\.json|bsaleWriteForCompany/))
test('Caylo sólo habilita TRANSFERENCIA 8', () => assert.match(migration, /d1000000-0000-0000-0000-000000000001', 8, 'TRANSFERENCIA', true/))
test('formas de pago pertenecen a company_id', () => assert.match(migration, /UNIQUE \(company_id, bsale_payment_type_id\)/))
test('RLS está habilitado en las cuatro tablas', () => assert.equal((migration.match(/ENABLE ROW LEVEL SECURITY/g) ?? []).length, 4))
test('tablas sensibles no tienen grants al navegador', () => assert.match(migration, /FROM PUBLIC, anon, authenticated/))
test('tarjetas priorizan deuda vencida y muestran total sólo si difiere', () => {
  assert.match(view, /Vencida \$\{money\(client\.overdueAmount\)\}/)
  assert.match(view, /Total \{money\(client\.totalAmount\)\}/)
})
test('selector de etapa usa Popover y conserva las cuatro etiquetas', () => {
  assert.match(view, /<Popover/)
  for (const label of ['Por gestionar', 'En gestión', 'Compromiso de pago', 'Seguimiento']) assert.match(view, new RegExp(label))
  assert.doesNotMatch(view, /id="collection-stage"[\s\S]*<select/)
})
test('compromiso y seguimiento exigen sus datos', () => {
  assert.match(view, /!commitmentAt \|\| !Number\.isFinite\(amount\) \|\| amount <= 0/)
  assert.match(view, /amount > client\.totalAmount/)
  assert.match(view, /!nextActionAt/)
})
test('bitácora filtra empresa y cliente, ordena reciente y limita carga', () => {
  assert.match(action, /getCollectionCustomerHistory\(clientId: number, requestedLimit = 20\)/)
  assert.match(action, /eq\('company_id', companyId\)\.eq\('client_id', clientId\)/)
  assert.match(action, /order\('created_at', \{ ascending: false \}\)\.limit\(limit \+ 1\)/)
  assert.match(action, /const hasMore = rows\.length > limit/)
})
test('bitácora resuelve actores agrupados y normaliza eventos', () => {
  assert.match(action, /schema\('portal'\).*from\('users'\)\.select\('id,nombre,apellido,email'\)\.in\('id', userIds\)/s)
  assert.match(action, /actorName: row\.created_by \? actorNames\.get\(row\.created_by\) \?\? 'Usuario' : 'Usuario'/)
  assert.match(action, /eventType: String\(row\.event_type\)/)
  assert.match(action, /commitmentDate:/)
  assert.match(action, /nextActionAt:/)
})
